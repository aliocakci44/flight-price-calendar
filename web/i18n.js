  /* "2026-12-07" -> full date formatted per language */
  function fullDate(ds) {
    var y = +ds.slice(0, 4), m = +ds.slice(5, 7), d = +ds.slice(8, 10);
    var w = wd()[(new Date(y, m - 1, d).getDay() + 6) % 7];
    return t("_datefmt")
      .split("{d}").join(String(d))
      .split("{month}").join(months()[m - 1])
      .split("{y}").join(String(y))
      .split("{wd}").join(w);
  }

