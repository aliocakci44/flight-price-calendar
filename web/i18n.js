  var cur = detect();

  function detect() {
    var saved = null;
    try { saved = localStorage.getItem("flex_lang"); } catch (e) { /* not set */ }
    if (saved && LANGS.indexOf(saved) >= 0) { return saved; }
    var cands = (navigator.languages || [navigator.language || "en"]);
    for (var i = 0; i < cands.length; i++) {
      var c = String(cands[i] || "").toLowerCase();
      if (LANGS.indexOf(c) >= 0) { return c; }
      var p = c.split("-")[0];
      if (LANGS.indexOf(p) >= 0) { return p; }
    }
    return "en";   // default when the browser language is not offered
  }

  function t(key, params) {
    var pack = D[cur] || D.en;
    var apack = A[cur] || A.en;
    var s = (pack[key] != null) ? pack[key] : apack[key];
    if (s == null) {
      s = (D.en[key] != null) ? D.en[key] : A.en[key];
    }
    if (s == null) { return key; }
    if (params) {
      for (var k in params) {
        if (Object.prototype.hasOwnProperty.call(params, k)) {
          s = s.split("{" + k + "}").join(String(params[k]));
        }
      }
    }
    return s;
  }

  function apply(root) {
    root = root || document;
    var nodes = root.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      nodes[i].textContent = t(nodes[i].getAttribute("data-i18n"));
    }
    nodes = root.querySelectorAll("[data-i18n-ph]");
    for (i = 0; i < nodes.length; i++) {
      nodes[i].setAttribute("placeholder",
                            t(nodes[i].getAttribute("data-i18n-ph")));
    }
    nodes = root.querySelectorAll("[data-i18n-title]");
    for (i = 0; i < nodes.length; i++) {
      nodes[i].setAttribute("title",
                            t(nodes[i].getAttribute("data-i18n-title")));
    }
    nodes = root.querySelectorAll("[data-i18n-aria]");
    for (i = 0; i < nodes.length; i++) {
      nodes[i].setAttribute("aria-label",
                            t(nodes[i].getAttribute("data-i18n-aria")));
    }
  }

